export function translate(
  language: Language,
  key: TranslationKey,
  values: Record<string, string | number> = {},
) {
  return Object.entries(values).reduce(
    (text, [k, v]) => text.replaceAll(`{${k}}`, String(v)),
    (language === 'zh' ? zh : en)[key] as string,
  )
}
export const I18nContext = createContext<{
  language: Language
  setLanguage: (value: Language) => void
}>({ language: 'en', setLanguage: () => {} })
export function useI18n() {
  const context = useContext(I18nContext)
  return {
    ...context,
    t: (key: TranslationKey, values?: Record<string, string | number>) =>
      translate(context.language, key, values),
  }
}
export function errorKey(error: unknown): TranslationKey {
  const message =
    error instanceof Error
      ? error.message
      : String((error as { message?: string })?.message || error)
  if (message in en) return message as TranslationKey
  const known = [
    'not_member',
    'not_allowed',
    'dish_unavailable',
    'invalid_options',
    'invalid_request',
    'invalid_name',
  ] as const
  return (
    known.find((k) => message.includes(k)) ||
    (/fetch|network|offline|Failed to send/i.test(message) ? 'networkError' : 'error')
  )
}
